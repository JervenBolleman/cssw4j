package swiss.sib.cssw4j.capi;

import org.graalvm.nativeimage.IsolateThread;
import org.graalvm.nativeimage.ObjectHandle;
import org.graalvm.nativeimage.ObjectHandles;
import org.graalvm.nativeimage.c.function.CEntryPoint;
import org.graalvm.nativeimage.c.type.CCharPointer;
import org.graalvm.nativeimage.c.type.CIntPointer;

import swiss.sib.cssw4j.Aligner;
import swiss.sib.cssw4j.Alignment;
import swiss.sib.cssw4j.Profile;
import swiss.sib.cssw4j.ScoringMatrix;

/**
 * C entry points of cssw4j, for building a native shared library with GraalVM Native Image.
 * <p>
 * The functions mirror the SSW C API: a query profile is built once with {@link #profileNew} and then aligned against
 * many references with {@link #align}. Sequences are passed as numbers, as in the C library: each letter is an index
 * into the substitution matrix, and the matrix is {@code n * n} scores in row-major order. Positions are 0-based.
 * <p>
 * The library is built by {@code src/native/build-native.sh} (or {@code mvn -Pnative package}). The C header
 * {@code libcssw4j.h} is generated by Native Image next to the library.
 */
public final class CApi {

	/** The result slots written by {@link #align}. */
	public static final int RESULT_SLOTS = 9;

	/** Returned by {@link #align} when the cigar buffer is too small; the required length is still written. */
	public static final int ERR_CIGAR_TOO_SMALL = -1;
	/** Returned by {@link #align} for an invalid profile or argument, or when the score overflows the profile. */
	public static final int ERR_INVALID = -2;

	private CApi() {
	}

	/** Compiles the query profile. The returned handle must be released with {@link #profileFree}. */
	@CEntryPoint(name = "cssw4j_profile_new")
	public static ObjectHandle profileNew(IsolateThread thread, CCharPointer read, int readLen, CCharPointer mat, int n,
			int scoreSize) {
		byte[] query = copy(read, readLen);
		byte[] matrix = copy(mat, n * n);
		ScoringMatrix m = ScoringMatrix.of(n, matrix, new byte[128]);
		Profile.ScoreSize size = switch (scoreSize) {
			case 0 -> Profile.ScoreSize.BYTE;
			case 1 -> Profile.ScoreSize.WORD;
			default -> Profile.ScoreSize.BOTH;
		};
		return ObjectHandles.getGlobal().create(Profile.of(query, readLen, m, size));
	}

	@CEntryPoint(name = "cssw4j_profile_free")
	public static void profileFree(IsolateThread thread, ObjectHandle profile) {
		ObjectHandles.getGlobal().destroy(profile);
	}

	/**
	 * Creates an aligner. An aligner holds scratch memory and must be used by one thread at a time; create one per
	 * thread.
	 */
	@CEntryPoint(name = "cssw4j_aligner_new")
	public static ObjectHandle alignerNew(IsolateThread thread) {
		return ObjectHandles.getGlobal().create(new Aligner());
	}

	@CEntryPoint(name = "cssw4j_aligner_free")
	public static void alignerFree(IsolateThread thread, ObjectHandle aligner) {
		ObjectHandles.getGlobal().destroy(aligner);
	}

	/**
	 * Aligns the profile's query against {@code ref}; the arguments and flags are those of {@code ssw_align}.
	 * <p>
	 * {@code out} receives {@link #RESULT_SLOTS} values: score1, score2, refBegin1, refEnd1, readBegin1, readEnd1,
	 * refEnd2, flag and cigarLen. The cigar is written to {@code cigar} (BAM packed, {@code cigarCap} entries); if it
	 * does not fit, {@link #ERR_CIGAR_TOO_SMALL} is returned and {@code cigarLen} still tells the required size.
	 *
	 * @return 0 on success, or one of the {@code ERR_*} codes
	 */
	@CEntryPoint(name = "cssw4j_align")
	public static int align(IsolateThread thread, ObjectHandle aligner, ObjectHandle profile, CCharPointer ref,
			int refLen, int gapOpen, int gapExtend, int flag, int filters, int filterd, int maskLen, CIntPointer out,
			CIntPointer cigar, int cigarCap) {
		try {
			Aligner a = ObjectHandles.getGlobal().get(aligner);
			Profile p = ObjectHandles.getGlobal().get(profile);
			byte[] target = copy(ref, refLen);
			Alignment r = a.align(p, target, refLen, gapOpen, gapExtend, flag, filters, filterd, maskLen);
			int[] path = r.cigar() == null ? new int[0] : r.cigar();
			out.write(0, r.score1());
			out.write(1, r.score2());
			out.write(2, r.refBegin1());
			out.write(3, r.refEnd1());
			out.write(4, r.readBegin1());
			out.write(5, r.readEnd1());
			out.write(6, r.refEnd2());
			out.write(7, r.flag());
			out.write(8, path.length);
			if (path.length > cigarCap) {
				return ERR_CIGAR_TOO_SMALL;
			}
			for (int i = 0; i < path.length; i++) {
				cigar.write(i, path[i]);
			}
			return 0;
		} catch (RuntimeException e) {
			return ERR_INVALID;
		}
	}

	private static byte[] copy(CCharPointer p, int length) {
		byte[] out = new byte[length];
		for (int i = 0; i < length; i++) {
			out[i] = p.read(i);
		}
		return out;
	}

	/** Not called from Java: Native Image needs a main method in the class that holds the entry points. */
	public static void main(String[] args) {
		System.err.println("cssw4j is a native library; call the cssw4j_* functions from C.");
	}
}
